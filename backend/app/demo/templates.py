def _city(
    category: str,
    title: str,
    short: str,
    description: str,
    venue: str | None,
    price: str,
    age: int,
    minutes: int,
    times: tuple[str, ...],
    *,
    indoor: str = "indoor",
    tags: tuple[str, ...] = (),
    sessions: int = 1,
    registration: bool = False,
) -> Template:
    """Городской шаблон привязан к одной площадке; None — место встречи указано в тексте."""
    return Template(
        category,
        title,
        short,
        description,
        ("city",) if venue else ("none",),
        price,
        age,
        minutes,
        times,
        indoor=indoor,
        tags=tags,
        sessions=sessions,
        registration=registration,
        only_venues=(venue,) if venue else (),
    )


